#!/usr/bin/env bash
# Renders the Helm chart into rendered/data-sync.yaml and refreshes the
# SECRET_CHECKSUM patch so a secret change rolls the pods.
# Usage: REDIS_PASSWORD=... ./render.sh && kustomize build .
set -euo pipefail
: "${REDIS_PASSWORD:?set REDIS_PASSWORD (use a dummy value for local validation)}"

HERE="$(cd "$(dirname "$0")" && pwd)"
CHART="$HERE/../../../helm/charts/data-sync"
ARGS=(data-sync "$CHART" --namespace data-sync
      -f "$CHART/values.yaml" -f "$CHART/values.production.yaml"
      --set-string redis.password="$REDIS_PASSWORD")

mkdir -p "$HERE/rendered"
helm template "${ARGS[@]}" > "$HERE/rendered/data-sync.yaml"

CHECKSUM="$(helm template "${ARGS[@]}" --show-only templates/secret.yaml | sha256sum | cut -d' ' -f1)"
cat > "$HERE/secret-checksum-patch.yaml" <<PATCH
# Regenerated by render.sh with sha256 of the rendered Secret manifest.
apiVersion: apps/v1
kind: Deployment
metadata:
  name: data-sync
spec:
  template:
    metadata:
      annotations:
        SECRET_CHECKSUM: "${CHECKSUM}"
PATCH
echo "Rendered. SECRET_CHECKSUM=${CHECKSUM}"
